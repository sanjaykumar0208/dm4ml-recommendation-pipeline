"""Build the final report PDF (reports/final_report.pdf) from the live results.

Pulls the real numbers from reports/evaluation_results.csv and
reports/validation_report.json so the report always matches the latest run.
"""
import json
from pathlib import Path

import pandas as pd
from reportlab.lib import colors
from reportlab.lib.enums import TA_JUSTIFY
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (
    Image, ListFlowable, ListItem, Paragraph, SimpleDocTemplate, Spacer, Table,
    TableStyle,
)

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

results = pd.read_csv(HERE / "evaluation_results.csv")
with open(HERE / "validation_report.json") as fh:
    vrep = json.load(fh)

styles = getSampleStyleSheet()
styles.add(ParagraphStyle("Body", parent=styles["Normal"], fontSize=9.5,
                          leading=13.5, alignment=TA_JUSTIFY, spaceAfter=6))
styles.add(ParagraphStyle("H2", parent=styles["Heading2"], fontSize=12.5,
                          textColor=colors.HexColor("#1e3a8a"), spaceBefore=10,
                          spaceAfter=4))
styles.add(ParagraphStyle("Sub", parent=styles["Normal"], fontSize=9,
                          textColor=colors.HexColor("#475569"), spaceAfter=10))
styles.add(ParagraphStyle("Small", parent=styles["Normal"], fontSize=8,
                          textColor=colors.HexColor("#64748b")))
H1 = ParagraphStyle("H1", parent=styles["Title"], fontSize=17,
                    textColor=colors.HexColor("#0f172a"), spaceAfter=2)

story = []

def P(t): story.append(Paragraph(t, styles["Body"]))
def H(t): story.append(Paragraph(t, styles["H2"]))

story.append(Paragraph("End-to-End Data Management Pipeline for a Recommendation System", H1))
story.append(Paragraph("DM4ML – Assignment 2 &nbsp;·&nbsp; Final Report", styles["Sub"]))

# ---- 1. Overview & objective ----
H("1. Objective and overview")
P("This project implements a modular, reproducible data-management pipeline for a "
  "<b>movie recommendation</b> system. The pipeline covers the full lifecycle: data "
  "ingestion, automated data-quality validation, preparation and transformation, "
  "feature management, model training with experiment tracking, model evaluation, and "
  "orchestration. The emphasis throughout is on a clean, restartable, well-documented "
  "pipeline rather than on maximising model accuracy alone.")
P("The dataset is generated by a <b>reproducible synthetic data generator</b> that mimics "
  "the MovieLens schema (users, items, user–item interactions with explicit ratings). "
  "Synthetic data was chosen so the whole pipeline is deterministic and runs end-to-end "
  "with no external downloads; because the schema matches MovieLens, real data can be "
  "substituted by dropping three CSVs into <font face='Courier'>data/raw/</font> and "
  "switching one config flag.")

# ---- 2. Design decisions ----
H("2. Key design decisions")
bullets = [
    ("Config-driven, modular stages.", "Every stage is an importable module with a "
     "single <font face='Courier'>run()</font> entry point; all paths, sizes and "
     "hyperparameters live in <font face='Courier'>configs/config.yaml</font>. Each stage "
     "persists its outputs, so any stage can be re-run or inspected independently and the "
     "pipeline is restartable."),
    ("Deliberate dirty-data injection.", "The generator corrupts a configurable fraction "
     "of interactions (missing ratings, out-of-range ratings, future timestamps, orphan "
     "foreign keys, duplicates) so the validation stage is exercised against genuine "
     "defects rather than trivially clean data."),
    ("Declarative validation with routing.", "Pandera schemas enforce types, nullability, "
     "ranges and enums; custom checks add future-timestamp detection, duplicate detection "
     "and referential integrity. Every rejected row is tagged with a human-readable reason "
     "and routed to <font face='Courier'>data/errors/</font> rather than silently dropped."),
    ("Time-based split, not random.", "Train/test are split on a timestamp quantile (test = "
     "most recent interactions). This avoids look-ahead leakage and mirrors production use — "
     "predicting the future from the past — which a random split would flatter."),
    ("Feature store for train/serve parity.", "User and item features are computed once and "
     "served through one lookup API used identically at training and prediction time, "
     "eliminating train/serve skew. A machine-readable feature catalog documents every feature."),
    ("Two contrasting models.", "A non-personalised popularity baseline and a personalised "
     "matrix-factorization model (FunkSVD with global/user/item biases, SGD) give a meaningful "
     "comparison across both ranking and rating-prediction metrics."),
]
items = [ListItem(Paragraph(f"<b>{h}</b> {b}", styles["Body"]), leftIndent=6) for h, b in bullets]
story.append(ListFlowable(items, bulletType="bullet", start="•", leftIndent=10))

# ---- 3. Tools ----
H("3. Tools used")
P("<b>Python, Pandas, NumPy</b> for data handling; <b>Pandera</b> for declarative data "
  "validation; a <b>custom file-based feature layer</b> (Parquet) for the feature store; "
  "<b>scikit-learn / NumPy</b> for modelling (the matrix-factorization model is a from-"
  "scratch SGD implementation for transparency); <b>MLflow</b> for experiment tracking "
  "(parameters, metrics, artifacts) on a SQLite backend; <b>Apache Airflow</b> for "
  "orchestration, with an equivalent plain-Python orchestrator for dependency-free runs; "
  "and <b>Parquet/CSV</b> for storage.")

# ---- architecture image ----
H("4. Pipeline architecture")
arch = HERE / "architecture.png"
if arch.exists():
    story.append(Image(str(arch), width=16.8 * cm, height=16.8 * cm * 1140 / 1770))
story.append(Paragraph("Figure 1. Pipeline stages, persisted data stores, experiment "
                       "tracking and the orchestration layer.", styles["Small"]))

# ---- 5. Data validation results ----
H("5. Data validation results")
it = vrep["interactions"]
P(f"On the default run the generator produced <b>{it['total_input']:,}</b> interaction rows; "
  f"validation accepted <b>{it['total_clean']:,}</b> and rejected <b>{it['total_errors']:,}</b> "
  f"({100*it['total_errors']/it['total_input']:.1f}%). Rejections broke down as: "
  f"schema/type/range/enum/null = {it['schema_type_range_enum_null_failures']}, "
  f"future timestamps = {it['future_timestamps']}, orphan user FKs = {it['orphan_user_fk']}, "
  f"orphan item FKs = {it['orphan_item_fk']}, duplicates = {it['duplicate_records']}. "
  "All rejected rows, each annotated with its failure reason, are written to "
  "<font face='Courier'>data/errors/</font>, and the summary to "
  "<font face='Courier'>reports/validation_report.json</font>.")

# ---- 6. Model evaluation ----
H("6. Model evaluation and comparison")
P("Both models were evaluated on the held-out (future) test split. Ranking metrics use "
  "top-K with binary relevance (an item is relevant if it appears in the user's test set); "
  "rating metrics are computed over the test interactions. The table reports K = 10.")

cols = ["model", "precision@10", "recall@10", "ndcg@10", "coverage@10", "diversity@10", "rmse", "mae"]
header = ["Model", "P@10", "R@10", "NDCG@10", "Cov@10", "Div@10", "RMSE", "MAE"]
data = [header]
for _, r in results.iterrows():
    data.append([str(r["model"])] + [f"{r[c]:.4f}" for c in cols[1:]])
tbl = Table(data, hAlign="LEFT", colWidths=[4.1*cm] + [1.55*cm]*7)
tbl.setStyle(TableStyle([
    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e3a8a")),
    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
    ("FONTSIZE", (0, 0), (-1, -1), 8),
    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
    ("ALIGN", (1, 0), (-1, -1), "CENTER"),
    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#eef2ff")]),
    ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#c7d2fe")),
    ("TOPPADDING", (0, 0), (-1, -1), 4),
    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
]))
story.append(tbl)
story.append(Spacer(1, 8))
P("<b>Analysis.</b> Matrix factorization wins decisively on rating-prediction accuracy "
  "(lower RMSE and MAE) and on catalogue coverage — it personalises recommendations across "
  "a far wider slice of the catalogue, whereas the popularity baseline repeatedly recommends "
  "the same head items (hence its low coverage). On top-K ranking the matrix-factorization "
  "model edges ahead on Precision@10 and NDCG@10. The popularity baseline remains a strong "
  "competitor at the very top ranks: because a handful of broadly-appealing items appear in "
  "many users' histories, always recommending them yields a non-trivial hit-rate. This "
  "popularity-vs-personalisation trade-off is a well-known and honest result in recommender "
  "systems — personalised models earn their keep on coverage, diversity and rating accuracy, "
  "not only on raw top-rank hit-rate. All parameters, the MF training-loss curve and every "
  "test metric above are tracked per model in MLflow.")

# ---- 7. Limitations ----
H("7. Limitations and future work")
lim = [
    "Synthetic data, while realistic in structure (latent user-taste and item-attribute "
    "vectors drive both choice and rating), cannot capture the full messiness of real user "
    "behaviour; validating on MovieLens / Amazon Reviews is the natural next step (supported "
    "by the CSV ingestion mode).",
    "The matrix-factorization model is a from-scratch SGD implementation chosen for "
    "transparency; production use would swap in a tuned library model (Surprise, LightFM, "
    "implicit) and add hyperparameter search.",
    "Absolute Precision/Recall values are modest, which is expected for a 300-item catalogue "
    "with top-10 lists and sparse held-out sets; the comparison between models is the "
    "informative signal.",
    "Cold-start users/items are filtered rather than modelled; a content-based or hybrid "
    "model would extend coverage to new users and items.",
    "The feature store is file-based; a managed store (Feast) would add point-in-time "
    "correctness and online serving for a production deployment.",
]
items = [ListItem(Paragraph(x, styles["Body"]), leftIndent=6) for x in lim]
story.append(ListFlowable(items, bulletType="bullet", start="•", leftIndent=10))

story.append(Spacer(1, 6))
story.append(Paragraph("Reproducibility: <font face='Courier'>python run_pipeline.py</font> "
             "regenerates every artifact deterministically from the committed seed. "
             "Experiment tracking: <font face='Courier'>mlflow ui --backend-store-uri "
             "sqlite:///mlflow.db</font>.", styles["Small"]))

doc = SimpleDocTemplate(
    str(HERE / "final_report.pdf"), pagesize=A4,
    leftMargin=1.8*cm, rightMargin=1.8*cm, topMargin=1.6*cm, bottomMargin=1.6*cm,
    title="DM4ML Assignment 2 - Final Report",
)
doc.build(story)
print("final_report.pdf written")
